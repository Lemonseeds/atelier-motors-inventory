import pg from 'pg';
import { schemaSql } from './sqlite.js';

/** Converts SQLite-style `?` placeholders to PostgreSQL `$1, $2, ...`. */
export function toPostgresPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

/**
 * Wraps any client with a pg-style `query(text, params) -> { rows, rowCount }`
 * method in the same small `prepare(sql).get/all/run`, `exec`, `close` interface
 * as better-sqlite3, so repositories work unchanged against either database.
 * Creates the schema on first use.
 */
export async function createPostgresAdapter(client) {
  await client.query(schemaSql('INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'));

  return {
    prepare(sql) {
      const text = toPostgresPlaceholders(sql);
      return {
        get: async (...params) => (await client.query(text, params)).rows[0],
        all: async (...params) => (await client.query(text, params)).rows,
        run: async (...params) => ({ changes: (await client.query(text, params)).rowCount }),
      };
    },
    exec: (sql) => client.query(sql),
    close: () => client.end(),
  };
}

/**
 * Connects to PostgreSQL (used for the hosted deployment on Render).
 * @param {string} connectionString e.g. process.env.DATABASE_URL
 */
export function createPostgresDatabase(connectionString) {
  return createPostgresAdapter(new pg.Pool({ connectionString }));
}
