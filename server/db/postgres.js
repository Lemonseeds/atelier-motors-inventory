import pg from 'pg';
import { schemaSql } from './sqlite.js';

/** Converts SQLite-style `?` placeholders to PostgreSQL `$1, $2, ...`. */
export function toPostgresPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

/**
 * Connects to PostgreSQL (used for the hosted deployment) and exposes the same
 * small `prepare(sql).get/all/run`, `exec`, `close` interface as better-sqlite3,
 * so repositories work unchanged against either database.
 * @param {string} connectionString e.g. process.env.DATABASE_URL
 */
export async function createPostgresDatabase(connectionString) {
  const pool = new pg.Pool({ connectionString });
  await pool.query(schemaSql('INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'));

  return {
    prepare(sql) {
      const text = toPostgresPlaceholders(sql);
      return {
        get: async (...params) => (await pool.query(text, params)).rows[0],
        all: async (...params) => (await pool.query(text, params)).rows,
        run: async (...params) => ({ changes: (await pool.query(text, params)).rowCount }),
      };
    },
    exec: (sql) => pool.query(sql),
    close: () => pool.end(),
  };
}
